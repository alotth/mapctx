#!/usr/bin/env node
/**
 * Build the SYNTHETIC GitHub fixtures (T-150).
 *
 *   node packages/provider/scripts/build-synthetic-fixtures.mjs
 *
 * Why these exist at all: the dependency read path is real and cheap, but every
 * issue reachable for this work has zero dependency edges, zero sub-issues and
 * no parent — the T-135 spike measured that across 16 issues in three
 * repositories, and the operator closed T-135 with that gap declared rather
 * than seeding a repository. A recorded fixture therefore proves the QUERY and
 * the cost, and proves nothing at all about the MAPPING.
 *
 * So the mapping is proved against hand-built payloads that are faithful to the
 * recorded shape, and labelled `synthetic` in the file so no later reader
 * mistakes them for measurements. They are generated by this script rather than
 * written by hand so the shape stays auditable against
 * `fixtures/github-recorded.json`.
 *
 * Covered, each because the mapping has a decision to get wrong:
 *   - `blockedBy` / `blocking` / `relatesTo` with real nodes, so the three
 *     relation kinds and their DIRECTION are exercised;
 *   - a sub-issue tree, which maps onto `blocks` and must not be dropped;
 *   - a nested connection GitHub cut off (`totalCount` > `nodes.length`), which
 *     must surface as a partial page with `omitted` naming it, because a
 *     truncated edge list read as "no dependencies" flattens a plan silently;
 *   - a `Status` of `Cancelled`, which the old `mapctx.toml` statusMap never
 *     covered and which the operator's 2026-10-14 decision requires.
 */

import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const HERE = path.dirname(fileURLToPath(import.meta.url))
const OUT_DIR = path.resolve(HERE, "..", "src", "github", "fixtures")

const PROJECT_ID = "PVT_kwHOSYNTHETIC00000"
const STATUS_FIELD_ID = "PVTSSF_lAHOSYNTHETIC00status"
const TITLE_FIELD_ID = "PVTF_lAHOSYNTHETIC00title"

const RATE_LIMIT = { limit: 5000, cost: 3, remaining: 4997, resetAt: "2026-10-14T18:00:00Z" }

function related(id, number, repo = "alotth/synthetic") {
  return { id, number, url: `https://github.com/${repo}/issues/${number}`, repository: { nameWithOwner: repo } }
}

/**
 * One issue in the recorded shape.
 *
 * `blockedByTotal` defaults to the number of nodes; passing a larger value is
 * how the truncation case is built, exactly as GitHub reports it.
 */
function issue({
  id,
  number,
  title,
  state = "OPEN",
  status,
  blockedBy = [],
  blocking = [],
  relatesTo = [],
  subIssues = [],
  blockedByTotal,
  subIssuesTotal,
  parent = null
}) {
  const fieldValues = [
    { __typename: "ProjectV2ItemFieldTextValue", text: title, field: { id: TITLE_FIELD_ID, name: "Title" } }
  ]
  if (status !== undefined) {
    fieldValues.push({
      __typename: "ProjectV2ItemFieldSingleSelectValue",
      optionId: `opt-${status.toLowerCase().replace(/\s+/g, "-")}`,
      name: status,
      field: { id: STATUS_FIELD_ID, name: "Status" }
    })
  }
  return {
    __typename: "Issue",
    id,
    number,
    title,
    url: `https://github.com/alotth/synthetic/issues/${number}`,
    state,
    stateReason: state === "CLOSED" ? "COMPLETED" : null,
    createdAt: "2026-10-01T00:00:00Z",
    updatedAt: "2026-10-10T12:00:00Z",
    closedAt: state === "CLOSED" ? "2026-10-09T12:00:00Z" : null,
    body: "Synthetic fixture body.",
    milestone: null,
    labels: { totalCount: 1, nodes: [{ name: "synthetic" }] },
    assignees: { totalCount: 1, nodes: [{ login: "octocat" }] },
    issueType: { name: "Task" },
    parent,
    subIssuesSummary: { total: subIssuesTotal ?? subIssues.length, completed: 0 },
    subIssues: { totalCount: subIssuesTotal ?? subIssues.length, nodes: subIssues },
    issueDependenciesSummary: {
      blockedBy: blockedBy.length,
      blocking: blocking.length,
      totalBlockedBy: blockedByTotal ?? blockedBy.length,
      totalBlocking: blocking.length
    },
    blockedBy: { totalCount: blockedByTotal ?? blockedBy.length, nodes: blockedBy },
    blocking: { totalCount: blocking.length, nodes: blocking },
    relatesTo: { totalCount: relatesTo.length, nodes: relatesTo },
    projectItems: {
      totalCount: 1,
      nodes: [
        {
          id: `PVTI_synthetic-${number}`,
          project: { id: PROJECT_ID, number: 99, title: "Synthetic board" },
          fieldValues: { totalCount: fieldValues.length, nodes: fieldValues }
        }
      ]
    }
  }
}

const ISSUE_A = "I_kwDOSYNTHETIC0000A"
const ISSUE_B = "I_kwDOSYNTHETIC0000B"
const ISSUE_C = "I_kwDOSYNTHETIC0000C"
const CHILD = "I_kwDOSYNTHETIC0child"
const TRUNCATED = "I_kwDOSYNTHETICtrunc"

// A is blocked by B, blocks C, relates to C, and has one sub-issue.
const a = issue({
  id: ISSUE_A,
  number: 1,
  title: "[T-901] blocked by one, blocking one, related to one",
  status: "In progress",
  blockedBy: [related(ISSUE_B, 2)],
  blocking: [related(ISSUE_C, 3)],
  relatesTo: [related(ISSUE_C, 3)],
  subIssues: [related(CHILD, 4)]
})

const b = issue({ id: ISSUE_B, number: 2, title: "[T-902] a blocker", status: "Done", state: "CLOSED" })

// The state the old statusMap could not express.
const c = issue({ id: ISSUE_C, number: 3, title: "[T-903] cancelled work", status: "Cancelled", state: "CLOSED" })

// GitHub returned two of five blockers and one of three sub-issues. The adapter
// must report the page partial and name what was cut, never imply completeness.
const truncated = issue({
  id: TRUNCATED,
  number: 5,
  title: "[T-905] more edges than one page holds",
  status: "Backlog",
  blockedBy: [related(ISSUE_B, 2), related(ISSUE_C, 3)],
  blockedByTotal: 5,
  subIssues: [related(CHILD, 4)],
  subIssuesTotal: 3
})

const entries = [
  { key: `node?id="${ISSUE_A}"`, label: "node", variables: { id: ISSUE_A }, data: { node: a, rateLimit: RATE_LIMIT } },
  { key: `node?id="${ISSUE_B}"`, label: "node", variables: { id: ISSUE_B }, data: { node: b, rateLimit: RATE_LIMIT } },
  { key: `node?id="${ISSUE_C}"`, label: "node", variables: { id: ISSUE_C }, data: { node: c, rateLimit: RATE_LIMIT } },
  {
    key: `node?id="${TRUNCATED}"`,
    label: "node",
    variables: { id: TRUNCATED },
    data: { node: truncated, rateLimit: RATE_LIMIT }
  },
  // A rate-limited refusal, so the retry-after path is exercised against a
  // provider-shaped error rather than a constructed one.
  {
    key: `node?id="I_kwDOSYNTHETIClimit"`,
    label: "node",
    variables: { id: "I_kwDOSYNTHETIClimit" },
    errors: [{ type: "RATE_LIMITED", message: "API rate limit exceeded for user ID 0." }],
    status: 200
  }
]

const file = {
  provenance: "synthetic",
  note:
    "HAND-BUILT, not recorded. Generated by packages/provider/scripts/build-synthetic-fixtures.mjs in the shape of " +
    "fixtures/github-recorded.json. These exist because every issue reachable for T-135/T-150 has zero dependency " +
    "edges and zero sub-issues, so a recorded fixture proves the query and the cost but not the mapping. Node ids " +
    "contain the word SYNTHETIC so they can never be mistaken for GitHub ids.",
  entries
}

fs.mkdirSync(OUT_DIR, { recursive: true })
const outPath = path.join(OUT_DIR, "github-synthetic.json")
fs.writeFileSync(outPath, `${JSON.stringify(file, null, 2)}\n`)
process.stdout.write(`wrote ${entries.length} synthetic entries to ${path.relative(process.cwd(), outPath)}\n`)
